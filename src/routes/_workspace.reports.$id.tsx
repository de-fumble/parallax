type Draft = { report: Report; layout: SectionKey[]; hidden: SectionKey[] };

// Blank lines left behind while editing shouldn't be saved as empty bullet points.
function tidy(report: Report): Report {
  const clean = (items: string[] | undefined) => (items ?? []).map((x) => x.trim()).filter(Boolean);
  return {
    ...report,
    research_title: report.research_title.trim(),
    warnings: clean(report.warnings),
    assumptions: clean(report.assumptions),
    evidence_gaps: clean(report.evidence_gaps),
    open_questions: clean(report.open_questions),
    recommended_next_searches: clean(report.recommended_next_searches),
    implications: (report.implications ?? []).filter((x) => x.implication.trim()),
    risks: (report.risks ?? []).filter((x) => x.risk.trim()),
    key_findings: (report.key_findings ?? []).filter((x) => x.finding.trim()),
    comparison: report.comparison && {
      ...report.comparison,
      options: report.comparison.options.map((o) => ({ ...o, strengths: clean(o.strengths), weaknesses: clean(o.weaknesses) })),
    },
  };
}

function ReportPage() {
  const { id } = Route.useParams();
  const { user, loading } = useAuth();
  const queryClient = useQueryClient();
  const workspace = useWorkspace();
  const query = useQuery({ ...reportQuery(id), enabled: !!user });
  const article = useRef<HTMLDivElement>(null);

  // Opening the report a run just produced retires the header's "Report ready" notice.
  const run = useResearchRun();
  const { dismiss } = useResearchActions();
  const justFinished = run.status === "done" && run.reportId === id;
  useEffect(() => {
    if (justFinished) void dismiss();
  }, [justFinished, dismiss]);

  // Editing works on a private copy; nothing changes for real until it is saved.
  const [draft, setDraft] = useState<Draft | null>(null);
  const [saving, setSaving] = useState(false);
  const started = useRef("");
  const keep = useRef<Set<SectionKey>>(new Set());
  const focusOn = useRef<string | null>(null);
  const dirty = draft !== null && JSON.stringify(draft) !== started.current;

  // Leaving the report abandons any edit in progress on it.
  useEffect(() => setDraft(null), [id]);

  // Entering edit mode by clicking a section lands the cursor in that section.
  useEffect(() => {
    if (!draft || !focusOn.current) return;
    const section = document.getElementById(`section-${focusOn.current}`);
    focusOn.current = null;
    section?.scrollIntoView({ block: "nearest" });
    section?.querySelector<HTMLTextAreaElement>("textarea")?.focus({ preventScroll: true });
  }, [draft]);

  // Closing the tab with unsaved edits asks first.
  useEffect(() => {
    if (!dirty) return;
    const warn = (e: BeforeUnloadEvent) => e.preventDefault();
    window.addEventListener("beforeunload", warn);
    return () => window.removeEventListener("beforeunload", warn);
  }, [dirty]);

  const row = query.data;
  const view = useMemo(() => (row ? viewOf(row) : null), [row]);

  const editor = useMemo<ReportEditor>(() => {
    const change = (fn: (d: Draft) => void) =>
      setDraft((current) => {
        if (!current) return current;
        const next = structuredClone(current);
        fn(next);
        return next;
      });
    return {
      update: (fn) => change((d) => fn(d.report)),
      // Swap with the neighbour that is actually on screen, skipping hidden and empty sections.
      move: (key, direction) =>
        change((d) => {
          const shown = d.layout.filter((k) => !d.hidden.includes(k) && (sectionHasContent(d.report, k) || keep.current.has(k)));
          const neighbour = shown[shown.indexOf(key) + direction];
          if (!neighbour) return;
          const a = d.layout.indexOf(key);
          const b = d.layout.indexOf(neighbour);
          d.layout[a] = neighbour;
          d.layout[b] = key;
        }),
      hide: (key) => change((d) => { d.hidden.push(key); }),
      show: (key) => change((d) => { d.hidden = d.hidden.filter((k) => k !== key); }),
    };
  }, []);

  if (!loading && !user) return <Shell><p><Link to="/auth" className="underline">Sign in</Link> to view this report.</p></Shell>;
  if (query.isError) {
    return (
      <Shell>
        <p>Couldn't load this report: {query.error.message}</p>
        <Button variant="outline" size="sm" className="mt-3" onClick={() => query.refetch()}>Try again</Button>
      </Shell>
    );
  }
  if (row === undefined || view === null) return <Shell><ReportSkeleton /></Shell>;
  if (row === null) return <Shell><p>Report not found. <Link to="/history" className="underline">Back to history</Link></p></Shell>;

  function startEditing(section?: string) {
    if (!view) return;
    const fresh: Draft = structuredClone({ report: view.report, layout: view.layout, hidden: view.hidden });
    started.current = JSON.stringify(fresh);
    keep.current = new Set(fresh.layout.filter((k) => sectionHasContent(fresh.report, k)));
    focusOn.current = section ?? null;
    setDraft(fresh);
  }

  // Write the edits (or null, to go back to the original) and update what is on screen.
  async function persist(edited: ReportEdits | null, done: string) {
    setSaving(true);
    const { data, error } = await supabase.from("reports").update({ edited: edited as never }).eq("id", id).select("id");
    setSaving(false);
    if (error || !data?.length) {
      toast.error("Couldn't save your changes", {
        description:
          error?.code === "42703" || error?.code === "42501" || error?.code === "PGRST204"
            ? "The database needs upgrading first: run supabase/schema.sql in the Supabase SQL Editor."
            : error?.message ?? "The report could not be updated.",
        duration: 12000,
      });
      return;
    }
    queryClient.setQueryData(reportQuery(id).queryKey, (current: ReportDetail | null | undefined) => (current ? { ...current, edited } : current));
    void queryClient.invalidateQueries({ queryKey: ["reports"] });
    setDraft(null);
    toast.success(done);
  }

  const save = () => {
    if (!draft) return;
    void persist({ report: tidy(draft.report), layout: draft.layout, hidden: draft.hidden, saved_at: new Date().toISOString() }, "Changes saved");
  };

  const shown = draft ?? view;
  // A personal report is its author's. In an organization every member can
  // read a report, but only its author and the people who run the organization may change it.
  const role = workspace.organizations.find((o) => o.id === row.org_id)?.role;
  const canChange = row.user_id === user?.id || canManage(role);

  return (
    <Shell outline={<ReportOutline container={article} floating={!draft} revision={`${id}|${shown.layout.join()}|${shown.hidden.join()}|${draft ? "edit" : "read"}`} />}>
      {/* Long URLs and unbroken strings wrap rather than push the page sideways. */}
      <div ref={article} className={`animate-in fade-in duration-300 [overflow-wrap:anywhere] ${draft ? "pb-28 md:pb-0" : ""}`}>
        {draft ? (
          // Pinned to the bottom edge on a phone, within thumb reach; a bar under the header on larger screens.
          <div className="pb-safe fixed inset-x-0 bottom-0 z-30 flex items-center justify-between gap-3 border-t border-foreground bg-background px-4 pt-3 shadow-sm md:sticky md:inset-x-auto md:bottom-auto md:top-14 md:z-20 md:-mx-2 md:flex-wrap md:border md:py-3 lg:top-15 lg:px-6 lg:py-3.5 lg:border-border/80 lg:bg-background/90 lg:backdrop-blur-md lg:shadow-xs print:hidden">
            <div className="min-w-0">
              <div className="text-sm font-medium tracking-tight">Editing report</div>
              <div className="truncate text-xs text-muted-foreground md:whitespace-normal">
                {dirty ? "You have unsaved changes." : <><span className="md:hidden">Tap any text to change it.</span><span className="hidden md:inline">Click any text to change it. Use the arrows to move a section.</span></>}
              </div>
            </div>
            <div className="flex shrink-0 gap-2">
              <Button variant="ghost" size="sm" disabled={saving} onClick={() => setDraft(null)}>
                {dirty ? <><span className="sm:hidden">Discard</span><span className="hidden sm:inline">Discard changes</span></> : "Cancel"}
              </Button>
              <Button size="sm" disabled={saving || !dirty} onClick={save}>
                {saving && <Loader2 className="animate-spin" />}
                <span className="sm:hidden">Save</span>
                <span className="hidden sm:inline">Save changes</span>
              </Button>
            </div>
          </div>
        ) : (
          <ReportToolbar
            id={id}
            source={{ topic: row.topic, created_at: row.created_at, report: view.report, layout: view.layout, hidden: view.hidden }}
            context={row.user_context}
            edited={view.isEdited}
            canChange={canChange}
            onEdit={() => startEditing()}
            onReset={() => void persist(null, "Restored the original report")}
          />
        )}

        <PrintOnlyLogo />
        <ReportDocument
          report={shown.report}
          topic={row.topic}
          createdAt={row.created_at}
          layout={shown.layout}
          hidden={shown.hidden}
          editor={draft ? editor : undefined}
          keep={draft ? keep.current : undefined}
          onEditRequest={draft || !canChange ? undefined : startEditing}
        />
      </div>
    </Shell>
  );
}

function ReportSkeleton() {
  return (
    <div aria-label="Loading report">
      <div className="flex gap-2">
        <Skeleton className="h-5 w-16" />
        <Skeleton className="h-5 w-20" />
        <Skeleton className="h-5 w-32" />
      </div>
      <Skeleton className="mt-5 h-11 w-4/5" />
      <Skeleton className="mt-3 h-4 w-1/2" />
      <div className="mt-8 space-y-2.5 border-l-2 border-border pl-5">
        <Skeleton className="h-3 w-24" />
        <Skeleton className="h-5 w-full" />
        <Skeleton className="h-5 w-11/12" />
        <Skeleton className="h-5 w-2/3" />
      </div>
      <Skeleton className="mt-12 h-7 w-40" />
      <div className="mt-5 space-y-5">
        {[0, 1, 2].map((i) => (
          <div key={i} className="space-y-2">
            <Skeleton className="h-4 w-full" />
            <Skeleton className="h-4 w-5/6" />
            <Skeleton className="h-4 w-20" />
          </div>
        ))}
      </div>
    </div>
  );
}

function Shell({ children, outline }: { children: ReactNode; outline?: ReactNode }) {
  return (
    <div className="mx-auto grid w-full max-w-6xl gap-10 px-4 py-6 sm:px-6 sm:py-10 lg:px-8 lg:py-12 xl:max-w-7xl xl:gap-14 xl:grid-cols-[minmax(0,1fr)_16rem] 2xl:max-w-[86rem] 2xl:gap-20 2xl:grid-cols-[minmax(0,1fr)_18rem]">
      <div className="min-w-0 max-w-4xl 2xl:max-w-5xl">{children}</div>
      {outline}
    </div>
  );
}
